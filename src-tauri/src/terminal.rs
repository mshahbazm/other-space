//! Claude Code in a terminal as an account: a generated activate script per
//! account (sh on macOS/Linux, PowerShell on Windows), and a terminal window
//! that loads it and starts `claude`.

use crate::claude::{self, CONFIG_ENV};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

/// Write a `claude` shim (macOS/Linux) or note the folder to add to PATH
/// (Windows) when `claude` isn't on PATH but was found elsewhere.
fn cli_dir_to_add(script_dir: &Path) -> Result<Option<PathBuf>, String> {
    let Some(claude::CliLocation::At(real)) = claude::resolve_cli() else {
        return Ok(None);
    };
    #[cfg(unix)]
    {
        let shim_dir = script_dir.join("bin");
        fs::create_dir_all(&shim_dir).map_err(|e| e.to_string())?;
        let link = shim_dir.join("claude");
        let _ = fs::remove_file(&link);
        std::os::unix::fs::symlink(&real, &link).map_err(|e| e.to_string())?;
        Ok(Some(shim_dir))
    }
    #[cfg(windows)]
    {
        let _ = script_dir;
        Ok(real.parent().map(Path::to_path_buf))
    }
}

// ---------- macOS / Linux ----------

#[cfg(unix)]
fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// (Re)generate an account's activate script. Sourcing it points `claude`
/// at the account: `config_dir` = Some(dir) exports `CLAUDE_CONFIG_DIR`, None
/// (the default account) unsets it so Claude Code uses `~/.claude`.
/// `script_dir` is where the script (and any `claude` shim) is written.
#[cfg(unix)]
pub fn write_activate_script(
    account_name: &str,
    config_dir: Option<&Path>,
    script_dir: &Path,
) -> Result<PathBuf, String> {
    fs::create_dir_all(script_dir).map_err(|e| e.to_string())?;
    let path = script_dir.join("activate");
    let mut lines = vec![
        "# Generated by Other — source this to use this Claude Code account.".to_string(),
        format!("export MULTIAPP_PROFILE={}", sh_quote(account_name)),
        format!("export MULTIAPP_ACTIVATE={}", sh_quote(&path.to_string_lossy())),
        // Tell the bash folder hook this directory is already handled, so an
        // explicit account choice isn't switched back at the next prompt.
        "_multiapp_pwd=\"$PWD\"".to_string(),
    ];
    match config_dir {
        Some(dir) => lines.push(format!("export {CONFIG_ENV}={}", sh_quote(&dir.to_string_lossy()))),
        None => lines.push(format!("unset {CONFIG_ENV}")),
    }
    if let Some(dir) = cli_dir_to_add(script_dir)? {
        lines.push(format!("export PATH={}:\"$PATH\"", sh_quote(&dir.to_string_lossy())));
    }
    lines.push(format!(
        "echo \"Other — Claude Code account: {}\"",
        account_name.replace('"', "")
    ));
    fs::write(&path, lines.join("\n") + "\n").map_err(|e| e.to_string())?;
    Ok(path)
}

/// The shell command run in the new terminal: `cd` first so an explicit
/// account choice beats the folder's mapping, then activate and start
/// `claude`.
#[cfg(unix)]
fn shell_command(activate: &Path, dir: Option<&Path>) -> String {
    let mut cmd = String::new();
    if let Some(d) = dir {
        cmd.push_str(&format!("cd {} && ", sh_quote(&d.to_string_lossy())));
    }
    cmd.push_str(&format!(". {} && claude", sh_quote(&activate.to_string_lossy())));
    cmd
}

/// Open a Terminal.app window with the account active and start `claude`.
#[cfg(target_os = "macos")]
pub fn open_terminal(activate: &Path, dir: Option<&Path>) -> Result<(), String> {
    let osa = format!(
        "tell application \"Terminal\"\nactivate\ndo script \"{}\"\nend tell",
        shell_command(activate, dir).replace('\\', r"\\").replace('"', "\\\"")
    );
    let out = Command::new("/usr/bin/osascript")
        .args(["-e", &osa])
        .stdin(Stdio::null())
        .output()
        .map_err(|e| e.to_string())?;
    if out.status.success() {
        Ok(())
    } else {
        Err(String::from_utf8_lossy(&out.stderr).to_string())
    }
}

/// Terminal emulators to try on Linux, with the flag that runs a command.
/// `$TERMINAL` is tried first.
#[cfg(target_os = "linux")]
const LINUX_TERMINALS: &[(&str, &[&str])] = &[
    ("x-terminal-emulator", &["-e"]),
    ("gnome-terminal", &["--"]),
    ("konsole", &["-e"]),
    ("xfce4-terminal", &["-x"]),
    ("kitty", &[]),
    ("alacritty", &["-e"]),
    ("wezterm", &["start", "--"]),
    ("foot", &[]),
    ("xterm", &["-e"]),
];

#[cfg(target_os = "linux")]
fn on_path(bin: &str) -> bool {
    std::env::var_os("PATH")
        .map(|p| std::env::split_paths(&p).any(|d| d.join(bin).is_file()))
        .unwrap_or(false)
}

/// Open a terminal window with the account active and start `claude`. The
/// shell stays open (on that account) after `claude` exits.
#[cfg(target_os = "linux")]
pub fn open_terminal(activate: &Path, dir: Option<&Path>) -> Result<(), String> {
    let script = format!("{}; exec \"${{SHELL:-sh}}\"", shell_command(activate, dir));
    let user_choice = std::env::var("TERMINAL").ok().filter(|t| on_path(t));
    let (bin, flags): (String, &[&str]) = match user_choice {
        Some(t) => (t, &["-e"]),
        None => LINUX_TERMINALS
            .iter()
            .find(|(bin, _)| on_path(bin))
            .map(|(bin, flags)| (bin.to_string(), *flags))
            .ok_or("No terminal app found. Set $TERMINAL to your terminal's command.")?,
    };
    let mut child = Command::new(bin)
        .args(flags)
        .args(["sh", "-c", &script])
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .map_err(|e| e.to_string())?;
    std::thread::spawn(move || {
        let _ = child.wait();
    });
    Ok(())
}

// ---------- Windows ----------

#[cfg(windows)]
fn ps_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

/// (Re)generate an account's `activate.ps1`. Dot-sourcing it points `claude`
/// at the account (see the macOS/Linux version above).
#[cfg(windows)]
pub fn write_activate_script(
    account_name: &str,
    config_dir: Option<&Path>,
    script_dir: &Path,
) -> Result<PathBuf, String> {
    fs::create_dir_all(script_dir).map_err(|e| e.to_string())?;
    let path = script_dir.join("activate.ps1");
    let mut lines = vec![
        "# Generated by Other — dot-source this to use this Claude Code account.".to_string(),
        format!("$env:MULTIAPP_PROFILE = {}", ps_quote(account_name)),
        format!("$env:MULTIAPP_ACTIVATE = {}", ps_quote(&path.to_string_lossy())),
        // Tell the folder hook this directory is already handled (see above).
        "$global:_OtherPwd = $PWD.ProviderPath".to_string(),
    ];
    match config_dir {
        Some(dir) => lines.push(format!("$env:{CONFIG_ENV} = {}", ps_quote(&dir.to_string_lossy()))),
        None => lines.push(format!("Remove-Item Env:{CONFIG_ENV} -ErrorAction SilentlyContinue")),
    }
    if let Some(dir) = cli_dir_to_add(script_dir)? {
        lines.push(format!("$env:PATH = {} + ';' + $env:PATH", ps_quote(&dir.to_string_lossy())));
    }
    lines.push(format!("Write-Host {}", ps_quote(&format!("Other — Claude Code account: {account_name}"))));
    fs::write(&path, lines.join("\r\n") + "\r\n").map_err(|e| e.to_string())?;
    Ok(path)
}

/// Open a PowerShell window (in Windows Terminal when installed) with the
/// account active and start `claude`. `-ExecutionPolicy Bypass` applies to
/// that window only, so the generated script runs under default policies.
#[cfg(windows)]
pub fn open_terminal(activate: &Path, dir: Option<&Path>) -> Result<(), String> {
    use std::os::windows::process::CommandExt;
    const CREATE_NO_WINDOW: u32 = 0x0800_0000;

    let mut ps = String::new();
    if let Some(d) = dir {
        ps.push_str(&format!("Set-Location -LiteralPath {}; ", ps_quote(&crate::paths::display_path(d))));
    }
    ps.push_str(&format!(". {}; claude", ps_quote(&activate.to_string_lossy())));
    let ps_args = ["-NoExit", "-ExecutionPolicy", "Bypass", "-Command", ps.as_str()];

    let has_wt = Command::new("where.exe")
        .arg("wt.exe")
        .creation_flags(CREATE_NO_WINDOW)
        .output()
        .map(|o| o.status.success())
        .unwrap_or(false);
    let mut cmd = if has_wt {
        let mut c = Command::new("wt.exe");
        c.arg("powershell.exe").args(ps_args);
        c
    } else {
        let mut c = Command::new("cmd.exe");
        c.args(["/c", "start", "", "powershell.exe"]).args(ps_args);
        c
    };
    cmd.creation_flags(CREATE_NO_WINDOW)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null());
    let mut child = cmd.spawn().map_err(|e| e.to_string())?;
    std::thread::spawn(move || {
        let _ = child.wait();
    });
    Ok(())
}
