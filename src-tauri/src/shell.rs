//! The optional folder switching: a small hook loaded by the user's shell
//! (zsh or bash on macOS/Linux, PowerShell on Windows) that switches the
//! account `claude` uses when you enter a mapped folder.
//!
//! Other writes `~/.multiapp/projects.map` (one `<folder>\t<activate script>`
//! line per folder) and the hook script, and adds one clearly marked block
//! to the shell's startup file that loads the hook.

use crate::claude::CONFIG_ENV;
use crate::paths;
use serde::Serialize;
use std::fs;
use std::path::{Path, PathBuf};

const MARKER_START: &str = "# >>> Other: Claude Code folder switching >>>";
const MARKER_END: &str = "# <<< Other: Claude Code folder switching <<<";
/// Marker used by earlier versions; still recognised as installed.
const LEGACY_MARKER: &str = "# >>> multi-app shell integration >>>";

fn other_dir() -> Result<PathBuf, String> {
    let dir = paths::other_dir();
    fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    Ok(dir)
}

/// Write the folder→account map the hook reads.
pub fn write_folder_map(entries: &[(String, PathBuf)]) -> Result<(), String> {
    let map: String = entries
        .iter()
        .map(|(path, activate)| format!("{path}\t{}\n", activate.to_string_lossy()))
        .collect();
    fs::write(other_dir()?.join("projects.map"), map).map_err(|e| e.to_string())
}

/// Which shell the integration is for, as shown in the window.
#[derive(Serialize)]
pub struct ShellInfo {
    /// e.g. "zsh", "bash", "PowerShell"; None when the user's shell isn't
    /// supported (e.g. fish).
    pub shell: Option<String>,
    /// The startup file the line is added to, e.g. "~/.zshrc".
    pub file: Option<String>,
    pub installed: bool,
}

pub fn info() -> ShellInfo {
    let files = startup_files();
    ShellInfo {
        shell: shell_name(),
        file: files.first().map(|f| display_file(f)),
        installed: files.iter().any(|f| has_marker(f)),
    }
}

fn has_marker(file: &Path) -> bool {
    fs::read_to_string(file)
        .map(|s| s.contains(MARKER_START) || s.contains(LEGACY_MARKER))
        .unwrap_or(false)
}

fn display_file(file: &Path) -> String {
    match file.strip_prefix(paths::home()) {
        Ok(rel) if cfg!(unix) => format!("~/{}", rel.to_string_lossy()),
        _ => file.to_string_lossy().into_owned(),
    }
}

/// Add the marked block to the shell's startup file(s) (idempotent).
pub fn install() -> Result<(), String> {
    write_hook()?;
    let files = startup_files();
    if files.is_empty() {
        return Err("Folder switching works with zsh, bash and PowerShell. Your shell isn't one of them.".into());
    }
    for file in files {
        if has_marker(&file) {
            continue;
        }
        if let Some(parent) = file.parent() {
            fs::create_dir_all(parent).map_err(|e| e.to_string())?;
        }
        let existing = fs::read_to_string(&file).unwrap_or_default();
        let block = format!("\n{MARKER_START}\n{}\n{MARKER_END}\n", load_line());
        fs::write(&file, existing + &block).map_err(|e| format!("Couldn't update {}: {e}", file.display()))?;
    }
    Ok(())
}

// ---------- macOS / Linux: zsh and bash ----------

#[cfg(unix)]
fn shell_name() -> Option<String> {
    let shell = std::env::var("SHELL").unwrap_or_else(|_| "/bin/zsh".into());
    let name = Path::new(&shell).file_name()?.to_string_lossy().into_owned();
    matches!(name.as_str(), "zsh" | "bash").then_some(name)
}

#[cfg(unix)]
fn startup_files() -> Vec<PathBuf> {
    let home = paths::home();
    match shell_name().as_deref() {
        Some("zsh") => vec![home.join(".zshrc")],
        // macOS terminals start login shells, which read .bash_profile.
        Some("bash") if cfg!(target_os = "macos") => vec![home.join(".bash_profile")],
        Some("bash") => vec![home.join(".bashrc")],
        _ => vec![],
    }
}

#[cfg(unix)]
fn load_line() -> &'static str {
    r#"[ -f "$HOME/.multiapp/multiapp.sh" ] && . "$HOME/.multiapp/multiapp.sh""#
}

/// Write the hook. On entering a folder it activates the account owning the
/// longest-matching mapped folder; on leaving all mapped folders it clears
/// the account. When a shell starts it only activates, never clears, so a
/// terminal Other opened as a specific account stays on it.
#[cfg(unix)]
pub fn write_hook() -> Result<(), String> {
    let script = format!(
        r#"# Generated by Other — do not edit (rewritten on every change).
_multiapp_switch() {{
  local map="$HOME/.multiapp/projects.map"
  [ -f "$map" ] || return 0
  # Not `path`: in zsh that name is the array tied to $PATH.
  local best="" act="" dir activate
  while IFS=$'\t' read -r dir activate; do
    [ -n "$dir" ] || continue
    case "$PWD/" in
      "$dir"/*) if [ "${{#dir}}" -gt "${{#best}}" ]; then best="$dir"; act="$activate"; fi ;;
    esac
  done < "$map"
  if [ -n "$act" ]; then
    if [ "$MULTIAPP_ACTIVATE" != "$act" ] && [ -f "$act" ]; then
      . "$act"
    fi
  elif [ -n "$MULTIAPP_ACTIVATE" ] && [ "$1" != "init" ]; then
    unset {CONFIG_ENV} MULTIAPP_PROFILE MULTIAPP_ACTIVATE
  fi
}}
if [ -n "$ZSH_VERSION" ]; then
  autoload -U add-zsh-hook
  add-zsh-hook chpwd _multiapp_switch
elif [ -n "$BASH_VERSION" ]; then
  # bash has no "directory changed" hook; check before each prompt.
  _multiapp_prompt() {{
    [ "$PWD" = "$_multiapp_pwd" ] && return
    _multiapp_pwd="$PWD"
    _multiapp_switch
  }}
  case ";${{PROMPT_COMMAND:-}};" in
    *";_multiapp_prompt;"*) ;;
    *) PROMPT_COMMAND="_multiapp_prompt${{PROMPT_COMMAND:+;$PROMPT_COMMAND}}" ;;
  esac
  _multiapp_pwd="$PWD"
fi
_multiapp_switch init
"#
    );
    let dir = other_dir()?;
    fs::write(dir.join("multiapp.sh"), &script).map_err(|e| e.to_string())?;
    // Earlier versions' ~/.zshrc line loads this name.
    fs::write(dir.join("multiapp.zsh"), &script).map_err(|e| e.to_string())
}

// ---------- Windows: PowerShell ----------

#[cfg(windows)]
fn shell_name() -> Option<String> {
    Some("PowerShell".into())
}

/// The current user's profile for Windows PowerShell and, if installed,
/// PowerShell 7 — asked from PowerShell itself, since Documents may be
/// redirected (e.g. to OneDrive).
#[cfg(windows)]
fn startup_files() -> Vec<PathBuf> {
    use std::os::windows::process::CommandExt;
    const CREATE_NO_WINDOW: u32 = 0x0800_0000;
    ["powershell.exe", "pwsh.exe"]
        .iter()
        .filter_map(|exe| {
            let out = std::process::Command::new(exe)
                .args(["-NoProfile", "-NoLogo", "-Command", "$PROFILE.CurrentUserCurrentHost"])
                .creation_flags(CREATE_NO_WINDOW)
                .output()
                .ok()?;
            let path = String::from_utf8_lossy(&out.stdout).trim().to_string();
            (out.status.success() && !path.is_empty()).then(|| PathBuf::from(path))
        })
        .collect()
}

#[cfg(windows)]
fn load_line() -> &'static str {
    r#"if (Test-Path "$HOME\.multiapp\multiapp.ps1") { . "$HOME\.multiapp\multiapp.ps1" }"#
}

/// The PowerShell hook: same behaviour as the zsh/bash one, checked before
/// each prompt.
#[cfg(windows)]
pub fn write_hook() -> Result<(), String> {
    let script = format!(
        r#"# Generated by Other — do not edit (rewritten on every change).
function global:_OtherSwitch([switch]$Init) {{
  $map = Join-Path $HOME '.multiapp\projects.map'
  if (-not (Test-Path -LiteralPath $map)) {{ return }}
  $here = $PWD.ProviderPath.TrimEnd('\') + '\'
  $best = ''; $act = ''
  foreach ($line in Get-Content -LiteralPath $map) {{
    $parts = $line -split "`t", 2
    if ($parts.Count -lt 2) {{ continue }}
    $dir = $parts[0].TrimEnd('\')
    if ($here.StartsWith($dir + '\', [StringComparison]::OrdinalIgnoreCase) -and $dir.Length -gt $best.Length) {{
      $best = $dir; $act = $parts[1]
    }}
  }}
  if ($act) {{
    if ($env:MULTIAPP_ACTIVATE -ne $act -and (Test-Path -LiteralPath $act)) {{ . $act }}
  }} elseif ($env:MULTIAPP_ACTIVATE -and -not $Init) {{
    Remove-Item Env:{CONFIG_ENV}, Env:MULTIAPP_PROFILE, Env:MULTIAPP_ACTIVATE -ErrorAction SilentlyContinue
  }}
}}
if (-not $global:_OtherPrompt) {{
  $global:_OtherPrompt = $function:prompt
  function global:prompt {{
    $p = $PWD.ProviderPath
    if ($p -ne $global:_OtherPwd) {{ $global:_OtherPwd = $p; _OtherSwitch }}
    & $global:_OtherPrompt
  }}
}}
$global:_OtherPwd = $PWD.ProviderPath
_OtherSwitch -Init
"#
    );
    fs::write(other_dir()?.join("multiapp.ps1"), script).map_err(|e| e.to_string())
}

#[cfg(test)]
mod tests {
    #[test]
    fn writes_hook_map_and_activate_scripts() {
        let _guard = crate::test_env_lock();
        let sandbox = std::env::temp_dir().join("other-shelltest-home");
        let _ = std::fs::remove_dir_all(&sandbox);
        std::fs::create_dir_all(sandbox.join("proj/sub")).unwrap();
        std::env::set_var("HOME", &sandbox);

        super::write_hook().unwrap();
        let config = sandbox.join("work/.claude");
        let work = crate::terminal::write_activate_script("Work", Some(&config), &sandbox.join("work")).unwrap();
        let def = crate::terminal::write_activate_script("Default", None, &sandbox.join("default")).unwrap();
        let work_src = std::fs::read_to_string(&work).unwrap();
        let def_src = std::fs::read_to_string(&def).unwrap();

        #[cfg(unix)]
        {
            assert!(work_src.contains(&format!("export CLAUDE_CONFIG_DIR='{}'", config.display())));
            assert!(def_src.contains("unset CLAUDE_CONFIG_DIR"));
            assert!(sandbox.join(".multiapp/multiapp.sh").is_file());
        }
        #[cfg(windows)]
        {
            assert!(work_src.contains(&format!("$env:CLAUDE_CONFIG_DIR = '{}'", config.display())));
            assert!(def_src.contains("Remove-Item Env:CLAUDE_CONFIG_DIR"));
            assert!(sandbox.join(".multiapp/multiapp.ps1").is_file());
        }

        super::write_folder_map(&[(sandbox.join("proj").to_string_lossy().into_owned(), work)]).unwrap();
        assert!(sandbox.join(".multiapp/projects.map").is_file());
    }
}
